#!/usr/bin/env node
// PIKAS mascot assets: explicit, deterministic sync from the design source to the shipped copy.
//
//   node scripts/sync-mascot.mjs          copy docs/pikas-mascot-system/brand/mascot → packages/ui/assets/mascot
//                                         and regenerate src/mascot/assets.generated.ts from manifest.json
//   node scripts/sync-mascot.mjs --check  report every file that differs (or is missing/extra) and the
//                                         generated map's staleness; exit 1 on any drift, 0 when identical
//
// Nothing runs at build time. The design workspace stays the source of truth; this script is the only
// way the shipped copy changes, and --check is how a reviewer proves they are the same.
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync, existsSync, copyFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const repo = resolve(pkg, "../..");
const SOURCE = resolve(repo, "docs/pikas-mascot-system/brand/mascot");
const DEST = resolve(pkg, "assets/mascot");
const GENERATED = resolve(pkg, "src/mascot/assets.generated.ts");
const check = process.argv.includes("--check");

const walk = (dir, base = dir) => {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    if (name === ".DS_Store") continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full, base));
    else out.push(relative(base, full).split("\\").join("/"));
  }
  return out;
};
const sha = file => createHash("sha256").update(readFileSync(file)).digest("hex");

function generatedSource() {
  const manifest = JSON.parse(readFileSync(join(SOURCE, "manifest.json"), "utf8"));
  const files = new Map(); // import name → relative file
  const nameFor = file => "f_" + file.replace(/^.*\//, "").replace(/\.svg$/, "").replace(/[^a-z0-9]+/gi, "_");
  const entries = [];
  for (const asset of [...manifest.assets].sort((a, b) => a.id.localeCompare(b.id))) {
    files.set(nameFor(asset.file), asset.file);
    if (asset.motionFile) files.set(nameFor(asset.motionFile), asset.motionFile);
    entries.push(`  "${asset.id}": { file: ${nameFor(asset.file)}, motion: ${asset.motionFile ? nameFor(asset.motionFile) : "null"} },`);
  }
  for (const motion of [...manifest.motion].sort((a, b) => a.id.localeCompare(b.id))) files.set(nameFor(motion.file), motion.file);
  const imports = [...files.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, file]) => `import ${name} from "../../assets/mascot/${file}";`).join("\n");
  const motionEntries = [...manifest.motion].sort((a, b) => a.id.localeCompare(b.id)).map(m => `  "${m.id}": ${nameFor(m.file)},`).join("\n");
  return `// GENERATED by scripts/sync-mascot.mjs from docs/pikas-mascot-system/brand/mascot/manifest.json — do not edit.
// Static imports let each app's bundler serve only the files it references, from one shared copy.
/* eslint-disable */
${imports}

export type StaticAsset = string | { src: string; width?: number; height?: number };
export const assetFiles: Record<string, { file: StaticAsset; motion: StaticAsset | null }> = {
${entries.join("\n")}
};
export const motionFiles: Record<string, StaticAsset> = {
${motionEntries}
};
`;
}

const sourceFiles = walk(SOURCE);
if (!sourceFiles.length) { console.error(`No source assets at ${SOURCE}`); process.exit(2); }

if (check) {
  const destFiles = walk(DEST);
  const problems = [];
  for (const f of sourceFiles) {
    if (!destFiles.includes(f)) problems.push(`missing in shipped copy: ${f}`);
    else if (sha(join(SOURCE, f)) !== sha(join(DEST, f))) problems.push(`differs: ${f}`);
  }
  for (const f of destFiles) if (!sourceFiles.includes(f)) problems.push(`extra in shipped copy: ${f}`);
  const generated = existsSync(GENERATED) ? readFileSync(GENERATED, "utf8") : "";
  if (generated !== generatedSource()) problems.push("src/mascot/assets.generated.ts is stale (run the sync)");
  if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
  console.log(`mascot assets in sync: ${sourceFiles.length} files, generated map current`);
} else {
  rmSync(DEST, { recursive: true, force: true });
  for (const f of sourceFiles) { mkdirSync(dirname(join(DEST, f)), { recursive: true }); copyFileSync(join(SOURCE, f), join(DEST, f)); }
  mkdirSync(dirname(GENERATED), { recursive: true });
  writeFileSync(GENERATED, generatedSource());
  console.log(`copied ${sourceFiles.length} files to ${relative(repo, DEST)}; wrote ${relative(repo, GENERATED)}`);
}
