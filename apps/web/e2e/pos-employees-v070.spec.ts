test('management rejects School/POS crossover, stale updates and scope mismatches without financial writes', async ({ page, context }) => {
  test.setTimeout(90000); await login(page, context); await edit(page, 'Caja Demo', {});
  let state = await snapshot(page);
  const user = state.administration.users.find((u: { id: string }) => u.id === 'pos-1');
  const draft = { id: user.id, name: user.name, email: user.email, posRole: user.posRole, status: user.status, allowedRegisterIds: user.allowedRegisterIds };
  expect((await invoke(page, 'adminSavePosEmployee', [{ ...draft, email: 'admin.cafeteria@demo.pikas.do' }, draft])).ok).toBe(false);
  expect((await invoke(page, 'adminSavePosEmployee', [{ ...draft, name: 'Fresh' }, draft])).ok).toBe(true);
  expect((await invoke(page, 'adminSavePosEmployee', [{ ...draft, name: 'Stale' }, draft])).ok).toBe(false);
  expect((await invoke(page, 'adminUpdateStudent', [state.students[0]])).ok).toBe(false);
  expect((await invoke(page, 'adminSetPartnership', ['partner-active', 'pending'])).ok).toBe(false);
  await login(page, context, 'school_admin');
  expect((await invoke(page, 'adminSavePosEmployee', [{ ...draft, id: 'school-created' }])).ok).toBe(false);
  expect((await invoke(page, 'adminSetUserStatus', ['pos-1', 'active'])).ok).toBe(false);
  await login(page, context); state = await snapshot(page);
  state.administration.memberships.find((m: { userId: string }) => m.userId === 'ca-1').authorityScope.locationId = 'foreign';
  await page.evaluate(({ key, state }) => { localStorage.setItem(key, JSON.stringify(state)); window.dispatchEvent(new StorageEvent('storage', { key })); }, { key: demoKey, state });
  await expect(page.getByRole('alert').filter({ hasText: 'No tienes acceso al personal' })).toBeVisible();
  await expect(page.getByRole('article')).toHaveCount(0);
  expect((await invoke(page, 'adminSavePosEmployee', [{ ...draft, id: 'foreign-created' }])).ok).toBe(false);
  expect((await snapshot(page)).events).toEqual(state.events);
});
