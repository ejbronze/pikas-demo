import { test, expect, type Page, type BrowserContext } from '@playwright/test';
import { demoKey, invoke, snapshot } from './helpers';
async function login(page: Page, context: BrowserContext, role = 'cafeteria_admin') {
  const admin = role.endsWith('_admin');
  await context.request.post(admin ? '/api/auth/admin-login' : '/api/auth/login', { form: admin ? { identifier: role === 'school_admin' ? 'admin.escuela@demo.pikas.do' : 'admin.cafeteria@demo.pikas.do', password: 'pikas-demo' } : { role: 'pos', identifier: 'cafeteria@demo.pikas.do', password: 'pikas-demo' } });
  await page.goto(admin ? role === 'school_admin' ? '/admin/escuela' : '/admin/cafeteria/personal' : '/pos');
  if (role === 'cafeteria_admin') await expect(page.getByRole('button', { name: 'Agregar empleado' })).toBeEnabled();
}
async function edit(page: Page, name: string, changes: { name?: string; status?: string; role?: string; allowed?: boolean }) {
  await page.getByRole('button', { name: `Editar ${name}`, exact: true }).click();
  if (changes.name) await page.getByLabel('Nombre', { exact: true }).fill(changes.name);
  if (changes.status) await page.getByRole('combobox', { name: 'Estado', exact: true }).selectOption(changes.status);
  if (changes.role) await page.getByRole('combobox', { name: 'Rol POS', exact: true }).selectOption(changes.role);
  if (changes.allowed !== undefined) await page.getByRole('checkbox', { name: 'Caja 1', exact: true }).setChecked(changes.allowed);
  await page.getByRole('button', { name: 'Guardar empleado' }).click();
  await expect(page.getByRole('region', { name: 'Editar empleado POS' })).toBeHidden();
}
